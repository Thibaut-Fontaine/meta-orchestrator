//! Disaster recovery snapshots.
//!
//! If the workstation is destroyed, the VPS must still explain every project:
//! what it is, where its private repo lives, which milestone is active, what
//! todos are open, which human checks are pending, and how to resume.
//!
//! `RECOVERY.md` is written:
//! * per project by `mox milestone` (committed nowhere; gitignored);
//! * globally by `mox up` / `mox recovery --push`, then rsynced to
//!   `~/mox-remote/RECOVERY.md` and `~/mox-remote/<slug>/RECOVERY.md`.
//!
//! It never contains tokens, answers, environment variables or log contents.

use crate::checks;
use crate::config::Config;
use crate::exec::CommandRunner;
use crate::milestones;
use crate::model::{ProjectState, ProjectStatus};
use crate::state::State;
use crate::util::{display_path, truncate_chars};
use anyhow::Result;
use chrono::{DateTime, Utc};
use std::collections::BTreeMap;
use std::path::{Path, PathBuf};

#[derive(Debug, Clone, Default)]
pub struct Report {
    pub global: String,
    pub projects: BTreeMap<String, String>,
}

/// Render the global and per-project snapshots from persisted state.
pub fn render(cfg: &Config, state: &State, now: DateTime<Utc>) -> Report {
    let checks = crate::checks::load(&cfg.checks_file()).unwrap_or_default();
    let mut projects = BTreeMap::new();
    let mut sections = String::new();

    for project in state.ordered() {
        let text = project_report(cfg, project, &checks, now);
        sections.push_str(&format!(
            "\n### {} — {}{} · {}\n\n- repo: {}\n- recovery file: `{}/RECOVERY.md`\n- status: {}\n",
            project.slug,
            project.status.as_str(),
            if project.target.is_empty() {
                String::new()
            } else {
                format!(" [{}]", project.target)
            },
            progress_short(cfg, project, now),
            if project.repo_url.is_empty() {
                "(none)"
            } else {
                &project.repo_url
            },
            crate::remote::remote_dir(cfg, &project.slug),
            project.status.as_str()
        ));
        projects.insert(project.slug.clone(), text);
    }

    let mut global = String::new();
    global.push_str("# mox recovery\n\n");
    global.push_str(&format!(
        "_Generated {} · host {}_\n\n",
        now.to_rfc3339_opts(chrono::SecondsFormat::Secs, true),
        crate::host::HostProfile::detect().describe()
    ));
    global.push_str("## If the workstation is gone\n\n");
    global.push_str(
        "1. SSH to the VPS (`ssh vps-ovh` or the configured alias).\n\
         2. Read this file and each `~/mox-remote/<slug>/RECOVERY.md`.\n\
         3. On a new machine: install mox + opencode, run `gh auth login`, then\n   `git clone <private repo>` into `~/mox-projects/<slug>`.\n\
         4. Run `mox project adopt ~/mox-projects/<slug>` (if needed), then\n   `mox up --resume` or `mox up --only <slug>`.\n\
         5. `mox vps sync` fetches any detached work still on the VPS.\n\n\
         No secrets are included in this file. The private repository contains the\n\
         full task specification, answers and tests.\n",
    );
    global.push_str(&format!("\nProjects: {}\n", state.projects.len()));
    global.push_str(&sections);
    global.push_str("\n---\nGenerated by mox. Do not edit by hand.\n");

    Report { global, projects }
}

fn progress_short(_cfg: &Config, project: &ProjectState, now: DateTime<Utc>) -> String {
    let board = milestones::load_optional(&milestones::board_path(Path::new(&project.path)));
    match board {
        Some(board) => {
            let p = milestones::progress(&board, now);
            format!("{} · ETA {}", p.short(), p.compact_eta())
        }
        None => "-".to_string(),
    }
}

fn project_report(
    cfg: &Config,
    project: &ProjectState,
    checks: &crate::checks::CheckStore,
    now: DateTime<Utc>,
) -> String {
    let dir = Path::new(&project.path);
    let board = milestones::load_optional(&milestones::board_path(dir));
    let mut out = String::new();
    out.push_str(&format!("# Recovery — {}\n\n", project.slug));
    out.push_str(&format!(
        "_Generated {}_\n\n",
        now.to_rfc3339_opts(chrono::SecondsFormat::Secs, true)
    ));
    out.push_str(&format!(
        "- title: {}\n- status: {}\n- target: {}\n- attempts: {}\n- repo: {}\n- remote path: `{}`\n- local path: `{}`\n",
        redact(&project.title),
        project.status.as_str(),
        if project.target.is_empty() {
            "local"
        } else {
            &project.target
        },
        project.attempts,
        if project.repo_url.is_empty() {
            "(none)"
        } else {
            &project.repo_url
        },
        crate::remote::remote_dir(cfg, &project.slug),
        display_path(dir)
    ));
    if let Some(pid) = project.remote_pid {
        out.push_str(&format!("- detached remote pid: {pid}\n"));
    }
    if let Some(error) = &project.last_error {
        out.push_str(&format!(
            "- last error: {}\n",
            redact(&truncate_chars(error, 400))
        ));
    }

    if let Some(board) = &board {
        let p = milestones::progress(board, now);
        out.push_str(&format!(
            "\n## Progress\n\n{}/{} milestones · {}% · current: {} · ETA {}\n\n",
            p.done,
            p.total,
            p.percent,
            p.current.as_deref().unwrap_or("-"),
            p.compact_eta()
        ));
        out.push_str("| id | status | complexity | estimate | actual | title |\n");
        out.push_str("|---|---|---|---|---|---|\n");
        for milestone in &board.milestones {
            out.push_str(&format!(
                "| {} | {} | {} | {} | {} | {} |\n",
                milestone.id,
                milestone.status.as_str(),
                milestone.complexity.as_str(),
                crate::util::format_secs(milestone.estimate_secs),
                if milestone.actual_secs == 0 {
                    "-".to_string()
                } else {
                    crate::util::format_secs(milestone.actual_secs)
                },
                redact(&milestone.title)
            ));
            if !milestone.algorithmic_complexity.is_empty() {
                out.push_str(&format!(
                    "\n_algorithm: {}_\n",
                    redact(&milestone.algorithmic_complexity)
                ));
            }
        }
        let open: Vec<String> = board
            .milestones
            .iter()
            .filter(|m| {
                matches!(
                    m.status,
                    milestones::MilestoneStatus::InProgress | milestones::MilestoneStatus::Pending
                )
            })
            .flat_map(|m| {
                m.todos
                    .iter()
                    .enumerate()
                    .filter(|(_, t)| !t.done)
                    .map(move |(i, t)| format!("- [ ] {} #{} {}", m.id, i + 1, redact(&t.text)))
            })
            .collect();
        out.push_str("\n## Open todos\n\n");
        if open.is_empty() {
            out.push_str("_none_\n");
        } else {
            out.push_str(&open.join("\n"));
            out.push('\n');
        }
    } else {
        out.push_str("\n## Progress\n\n_no MILESTONES.json at this path_\n");
    }

    let open_checks: Vec<String> = checks
        .open()
        .iter()
        .filter(|c| c.slug == project.slug)
        .map(|c| {
            format!(
                "- [ ] {} — {} ({}){}",
                c.id,
                redact(&c.title),
                checks::relative_label(c, now),
                c.probe
                    .as_deref()
                    .map(|p| format!(" · probe: {}", redact(p)))
                    .unwrap_or_default()
            )
        })
        .collect();
    if !open_checks.is_empty() {
        out.push_str("\n## Human checks\n\n");
        out.push_str(&open_checks.join("\n"));
        out.push('\n');
    }

    if let Ok(status) = std::fs::read_to_string(dir.join("STATUS.md")) {
        let excerpt: Vec<&str> = status
            .lines()
            .filter(|l| !l.trim().is_empty())
            .take(8)
            .collect();
        if !excerpt.is_empty() {
            out.push_str("\n## Last STATUS.md\n\n");
            for line in excerpt {
                out.push_str(&format!("{}\n", redact(line)));
            }
        }
    }

    out.push_str("\n## How to resume\n\n");
    out.push_str(&format!(
        "1. `ssh {}` (or install mox on a new machine).\n\
         2. Clone the private repo: `git clone {}`.\n\
         3. Place it under `~/mox-projects/{}`; `mox project adopt` if it is not in state.\n\
         4. `mox up --resume` (or `mox up --only {}`).\n\
         5. For detached work: `mox vps sync --slug {}`; stop it with `mox stop {}`.\n",
        cfg.ssh_alias,
        if project.repo_url.is_empty() {
            "<private repo URL from GitHub>"
        } else {
            &project.repo_url
        },
        project.slug,
        project.slug,
        project.slug,
        project.slug
    ));
    out.push_str(
        "\n_No secrets are stored here. The private repo has TASK.md, TASKS.md and answers._\n",
    );
    out
}

/// Write one project's recovery file from its board only (used by `mox milestone`
/// even on a remote host with no local state).
pub fn write_board_recovery(
    board: &milestones::Board,
    project_dir: &Path,
    now: DateTime<Utc>,
) -> Result<PathBuf> {
    let mut out = String::new();
    out.push_str(&format!("# Recovery — {}\n\n", board.slug));
    out.push_str(&format!(
        "_Generated {} · updated by `mox milestone`_\n\n",
        now.to_rfc3339_opts(chrono::SecondsFormat::Secs, true)
    ));
    let p = milestones::progress(board, now);
    out.push_str(&format!(
        "Progress: {}/{} · {}% · current: {} · ETA {}\n\n",
        p.done,
        p.total,
        p.percent,
        p.current.as_deref().unwrap_or("-"),
        p.compact_eta()
    ));
    out.push_str("| id | status | complexity | estimate | actual | title |\n");
    out.push_str("|---|---|---|---|---|---|\n");
    for milestone in &board.milestones {
        out.push_str(&format!(
            "| {} | {} | {} | {} | {} | {} |\n",
            milestone.id,
            milestone.status.as_str(),
            milestone.complexity.as_str(),
            crate::util::format_secs(milestone.estimate_secs),
            if milestone.actual_secs == 0 {
                "-".to_string()
            } else {
                crate::util::format_secs(milestone.actual_secs)
            },
            redact(&milestone.title)
        ));
        if milestone.status == milestones::MilestoneStatus::Blocked && !milestone.note.is_empty() {
            out.push_str(&format!("\n_blocked: {}_\n", redact(&milestone.note)));
        }
    }
    out.push_str("\n## Open todos\n\n");
    let mut any = false;
    for milestone in &board.milestones {
        for (i, todo) in milestone.todos.iter().enumerate() {
            if !todo.done {
                any = true;
                out.push_str(&format!(
                    "- [ ] {} #{} {}\n",
                    milestone.id,
                    i + 1,
                    redact(&todo.text)
                ));
            }
        }
    }
    if !any {
        out.push_str("_none_\n");
    }
    out.push_str("\n## How to resume\n\n");
    out.push_str(
        "1. Inspect `STATUS.md`, `TASKS.md`, `CHECKS.md` and the private repository.\n\
         2. Install mox + opencode on a new machine, run `gh auth login`.\n\
         3. Clone the private repo into `~/mox-projects/<slug>`.\n\
         4. `mox project adopt` (if needed), then `mox up --resume`.\n\
         5. For detached runs: `mox vps sync --slug <slug>`.\n",
    );
    out.push_str("\n_No secrets are stored here._\n");
    ensure_git_exclude(project_dir);
    let path = project_dir.join("RECOVERY.md");
    crate::util::write_private(&path, out)?;
    Ok(path)
}

/// Keep the root RECOVERY.md out of git for adopted repositories that do not
/// have the scaffolded .gitignore.
fn ensure_git_exclude(project_dir: &Path) {
    let Some(git_dir) = project_dir
        .join(".git")
        .is_dir()
        .then_some(project_dir.join(".git"))
    else {
        return;
    };
    let info = git_dir.join("info");
    if std::fs::create_dir_all(&info).is_err() {
        return;
    }
    let exclude = info.join("exclude");
    let current = std::fs::read_to_string(&exclude).unwrap_or_default();
    if !current.lines().any(|line| line.trim() == "RECOVERY.md") {
        let _ = std::fs::write(&exclude, format!("{current}\nRECOVERY.md\n"));
    }
}

/// Write local copies under the state dir.
pub fn write_local(cfg: &Config, report: &Report) -> Result<Vec<PathBuf>> {
    let dir = cfg.state_dir_path().join("recovery");
    crate::util::ensure_dir_private(&dir)?;
    let mut paths = Vec::new();
    let global = dir.join("RECOVERY.md");
    crate::util::write_private(&global, &report.global)?;
    paths.push(global);
    for (slug, text) in &report.projects {
        let path = dir.join(format!("{slug}.md"));
        crate::util::write_private(&path, text)?;
        paths.push(path);
    }
    Ok(paths)
}

/// Push snapshots to the VPS. Returns the number of files copied.
pub fn push(runner: &dyn CommandRunner, cfg: &Config, report: &Report) -> Result<usize> {
    let alias = &cfg.ssh_alias;
    let root = crate::remote::remote_root(cfg);
    let root_cmd = format!("mkdir -p {root}");
    let output = runner.run(&crate::remote::ssh_spec(cfg, alias, &root_cmd, 30))?;
    if !output.success() {
        anyhow::bail!("could not create {root} on the VPS: {}", output.tail(4));
    }
    let dir = cfg.state_dir_path().join("recovery");
    let mut count = 0usize;
    for slug in report.projects.keys() {
        let remote_dir = crate::remote::remote_dir(cfg, slug);
        let mkdir = format!("mkdir -p {remote_dir}");
        let output = runner.run(&crate::remote::ssh_spec(cfg, alias, &mkdir, 30))?;
        if !output.success() {
            anyhow::bail!("could not create {remote_dir}: {}", output.tail(4));
        }
        let local = dir.join(format!("{slug}.md"));
        let remote = format!("{remote_dir}/RECOVERY.md");
        let output = runner.run(&crate::remote::rsync_file_to_spec(
            cfg, alias, &remote, &local,
        ))?;
        if !output.success() {
            anyhow::bail!("could not push {remote}: {}", output.tail(4));
        }
        count += 1;
    }
    let local_global = dir.join("RECOVERY.md");
    let remote_global = format!("{root}/RECOVERY.md");
    let output = runner.run(&crate::remote::rsync_file_to_spec(
        cfg,
        alias,
        &remote_global,
        &local_global,
    ))?;
    if !output.success() {
        anyhow::bail!("could not push {remote_global}: {}", output.tail(4));
    }
    count += 1;
    Ok(count)
}

/// Render, write locally and push everything. Best effort at call sites.
pub fn sync_all(runner: &dyn CommandRunner, cfg: &Config) -> Result<usize> {
    let state = crate::state::load(&cfg.state_file())?;
    let report = render(cfg, &state, Utc::now());
    write_local(cfg, &report)?;
    push(runner, cfg, &report)
}

/// Read-only report of remote recovery file ages (seconds).
pub fn remote_ages(
    runner: &dyn CommandRunner,
    cfg: &Config,
    state: &State,
) -> Result<Vec<(String, Option<u64>)>> {
    let mut paths = vec![format!("{}/RECOVERY.md", crate::remote::remote_root(cfg))];
    let mut names = vec!["global".to_string()];
    for project in state.ordered() {
        names.push(project.slug.clone());
        paths.push(format!(
            "{}/RECOVERY.md",
            crate::remote::remote_dir(cfg, &project.slug)
        ));
    }
    let output = runner.run(&crate::remote::remote_stat_spec(
        cfg,
        &cfg.ssh_alias,
        &paths,
    ))?;
    if !output.success() {
        anyhow::bail!("recovery check failed: {}", output.tail(4));
    }
    let mut ages = Vec::new();
    for (index, name) in names.iter().enumerate() {
        let marker = format!("FILE={} ", paths[index]);
        let age = output
            .stdout
            .lines()
            .find(|line| line.starts_with(&marker))
            .and_then(|line| line.split("AGE=").nth(1))
            .and_then(|v| v.trim().parse::<u64>().ok());
        ages.push((name.clone(), age));
    }
    Ok(ages)
}

/// Redact obvious token shapes from text before it lands in a recovery file.
pub fn redact(text: &str) -> String {
    let mut out = String::with_capacity(text.len());
    let mut chars = text.chars().peekable();
    while let Some(ch) = chars.next() {
        out.push(ch);
        // Keep it simple: mask the tail of known prefixes when we see them.
        let tail: String = chars.clone().take(48).collect();
        for prefix in ["ghp_", "github_pat_", "sk-", "AKIA", "xoxb-", "xoxp-"] {
            if out.ends_with(prefix) && tail.len() >= 8 {
                for _ in 0..tail.chars().count().min(40) {
                    chars.next();
                }
                out.push_str("<redacted>");
                break;
            }
        }
    }
    out
}

/// Helper for tests and `mox recovery` output.
pub fn summary_counts(state: &State) -> (usize, usize) {
    let running = state
        .projects
        .values()
        .filter(|p| p.status == ProjectStatus::Running)
        .count();
    (state.projects.len(), running)
}

#[cfg(test)]
mod tests {
    use super::*;
    use crate::model::{Idea, ProjectSpec, ProjectState};

    fn cfg(root: &Path) -> Config {
        Config {
            projects_root: root.join("projects").display().to_string(),
            state_dir: root.join("state").display().to_string(),
            ..Config::default()
        }
    }

    fn seeded(root: &Path) -> (Config, State) {
        let cfg = cfg(root);
        let project_dir = cfg.projects_root_path().join("demo");
        std::fs::create_dir_all(&project_dir).unwrap();
        let spec = ProjectSpec::from_idea(
            &Idea {
                title: Some("Demo".into()),
                details: "demo".into(),
                raw: String::new(),
            },
            "demo".into(),
        );
        let mut spec = spec;
        spec.milestones = milestones::fallback_for(&spec);
        let mut board = milestones::board_from_spec(&spec, Utc::now());
        milestones::start(&mut board, "m1", Utc::now()).unwrap();
        milestones::save(&milestones::board_path(&project_dir), &board).unwrap();
        std::fs::write(
            project_dir.join("STATUS.md"),
            "Working: parser\nNext: tests\n",
        )
        .unwrap();
        std::fs::write(project_dir.join("TASKS.md"), "- [ ] parser\n").unwrap();
        let mut state = State::default();
        let mut project =
            ProjectState::new("demo", "Demo project", &project_dir.display().to_string());
        project.status = ProjectStatus::Running;
        project.target = "vps".into();
        project.repo_url = "https://github.com/me/demo".into();
        project.remote_pid = Some(4242);
        state.upsert(project);
        crate::state::save(&cfg.state_file(), &state).unwrap();
        (cfg, state)
    }

    #[test]
    fn global_and_project_reports_contain_recovery_information() {
        let dir = tempfile::tempdir().unwrap();
        let (cfg, state) = seeded(dir.path());
        let report = render(&cfg, &state, Utc::now());
        assert!(report.global.contains("If the workstation is gone"));
        assert!(report.global.contains("https://github.com/me/demo"));
        assert!(report.global.contains("demo"));
        let project = report.projects.get("demo").unwrap();
        assert!(project.contains("Recovery — demo"));
        assert!(project.contains("m1"));
        assert!(project.contains("Open todos"));
        assert!(project.contains("How to resume"));
        assert!(project.contains("4242"));
        assert!(project.contains("Working: parser"));
        assert!(!project.contains("ghp_"));
    }

    #[test]
    fn push_copies_global_and_project_files() {
        use crate::exec::FakeRunner;
        let dir = tempfile::tempdir().unwrap();
        let (cfg, state) = seeded(dir.path());
        let report = render(&cfg, &state, Utc::now());
        let runner = FakeRunner::ok();
        let count = push(&runner, &cfg, &report).unwrap();
        assert_eq!(count, 2);
        let displays = runner.displays();
        assert!(displays
            .iter()
            .any(|d| d.contains("~/mox-remote/RECOVERY.md")));
        assert!(displays
            .iter()
            .any(|d| d.contains("~/mox-remote/demo/RECOVERY.md")));
    }

    #[test]
    fn local_snapshots_are_private() {
        let dir = tempfile::tempdir().unwrap();
        let (cfg, state) = seeded(dir.path());
        let report = render(&cfg, &state, Utc::now());
        let paths = write_local(&cfg, &report).unwrap();
        assert_eq!(paths.len(), 2);
        #[cfg(unix)]
        {
            use std::os::unix::fs::PermissionsExt;
            for path in paths {
                assert_eq!(
                    std::fs::metadata(&path).unwrap().permissions().mode() & 0o777,
                    0o600
                );
            }
        }
    }

    #[test]
    fn board_recovery_is_written_for_remote_agents() {
        let dir = tempfile::tempdir().unwrap();
        let spec = ProjectSpec::from_idea(
            &Idea {
                title: Some("X".into()),
                details: "x".into(),
                raw: String::new(),
            },
            "x".into(),
        );
        let mut spec = spec;
        spec.milestones = milestones::fallback_for(&spec);
        let board = milestones::board_from_spec(&spec, Utc::now());
        let path = write_board_recovery(&board, dir.path(), Utc::now()).unwrap();
        let text = std::fs::read_to_string(path).unwrap();
        assert!(text.contains("Recovery — x"));
        assert!(text.contains("Open todos"));
        assert!(text.contains("How to resume"));
    }

    #[test]
    fn redacts_common_tokens() {
        let text = redact("token ghp_abcdefghijklmnopqrstuvwxyz0123456789 and sk-abcdefghijklmnop");
        assert!(!text.contains("ghp_abc"));
        assert!(!text.contains("sk-abc"));
        assert!(text.contains("<redacted>"));
    }
}
