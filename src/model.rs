//! Domain types shared across modules.

use serde::{Deserialize, Serialize};
use std::collections::BTreeMap;

/// How much CPU/RAM a project is expected to need.
#[derive(Debug, Clone, Copy, PartialEq, Eq, Serialize, Deserialize, Default)]
#[serde(rename_all = "lowercase")]
pub enum ComputeNeed {
    #[default]
    Light,
    Medium,
    Heavy,
    Gpu,
}

impl ComputeNeed {
    pub fn as_str(&self) -> &'static str {
        match self {
            ComputeNeed::Light => "light",
            ComputeNeed::Medium => "medium",
            ComputeNeed::Heavy => "heavy",
            ComputeNeed::Gpu => "gpu",
        }
    }

    /// Suggested number of cores reserved for one agent with this need.
    pub fn preferred_cores(&self) -> usize {
        match self {
            ComputeNeed::Light => 1,
            ComputeNeed::Medium => 2,
            ComputeNeed::Heavy => 4,
            ComputeNeed::Gpu => 4,
        }
    }
}

impl std::str::FromStr for ComputeNeed {
    type Err = String;

    fn from_str(s: &str) -> Result<Self, Self::Err> {
        match s.trim().to_ascii_lowercase().as_str() {
            "light" | "low" => Ok(ComputeNeed::Light),
            "medium" | "normal" => Ok(ComputeNeed::Medium),
            "heavy" | "high" => Ok(ComputeNeed::Heavy),
            "gpu" => Ok(ComputeNeed::Gpu),
            other => Err(format!("unknown compute need `{other}`")),
        }
    }
}

/// Relative difficulty of one milestone, used to weight progress and ETA.
#[derive(Debug, Clone, Copy, PartialEq, Eq, Serialize, Deserialize, Default)]
#[serde(rename_all = "kebab-case")]
pub enum Complexity {
    Low,
    #[default]
    Medium,
    High,
    VeryHigh,
}

impl Complexity {
    pub fn as_str(&self) -> &'static str {
        match self {
            Complexity::Low => "low",
            Complexity::Medium => "medium",
            Complexity::High => "high",
            Complexity::VeryHigh => "very-high",
        }
    }

    /// Weight used by the progress/ETA calculation.
    pub fn weight(&self) -> u32 {
        match self {
            Complexity::Low => 1,
            Complexity::Medium => 2,
            Complexity::High => 3,
            Complexity::VeryHigh => 5,
        }
    }
}

impl std::str::FromStr for Complexity {
    type Err = String;

    fn from_str(s: &str) -> Result<Self, Self::Err> {
        match s.trim().to_ascii_lowercase().replace('_', "-").as_str() {
            "low" | "trivial" | "easy" => Ok(Complexity::Low),
            "medium" | "normal" => Ok(Complexity::Medium),
            "high" | "hard" => Ok(Complexity::High),
            "very-high" | "veryhigh" | "critical" => Ok(Complexity::VeryHigh),
            other => Err(format!(
                "unknown complexity `{other}` (use low, medium, high or very-high)"
            )),
        }
    }
}

/// One milestone in the plan (no runtime state; see `milestones::Milestone`).
#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize, Default)]
pub struct MilestoneSpec {
    #[serde(default)]
    pub id: String,
    #[serde(default)]
    pub title: String,
    #[serde(default)]
    pub description: String,
    #[serde(default)]
    pub todos: Vec<String>,
    #[serde(default)]
    pub complexity: Complexity,
    /// Big-O style note when the milestone involves a non-trivial algorithm.
    #[serde(default)]
    pub algorithmic_complexity: String,
    /// Planned duration in seconds.
    #[serde(default)]
    pub estimate_secs: u64,
}

/// One raw project idea supplied by the user.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct Idea {
    pub title: Option<String>,
    pub details: String,
    pub raw: String,
}

impl Idea {
    /// Text used for prompts and slug fallback.
    pub fn text(&self) -> &str {
        &self.details
    }
}

/// A clarifying question generated by the brain about one project.
#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize, Default)]
pub struct Question {
    #[serde(default)]
    pub id: String,
    #[serde(default)]
    pub question: String,
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub why: Option<String>,
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub default: Option<String>,
}

/// A fully specified project, ready to be scaffolded and run.
#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize)]
pub struct ProjectSpec {
    pub slug: String,
    pub title: String,
    pub idea: String,
    #[serde(default)]
    pub summary: String,
    #[serde(default)]
    pub questions: Vec<Question>,
    #[serde(default)]
    pub answers: BTreeMap<String, String>,
    #[serde(default)]
    pub acceptance_criteria: Vec<String>,
    #[serde(default)]
    pub assumptions: Vec<String>,
    #[serde(default)]
    pub risks: Vec<String>,
    #[serde(default)]
    pub stack: Vec<String>,
    #[serde(default)]
    pub compute: ComputeNeed,
    #[serde(default)]
    pub needs_vps: bool,
    #[serde(default)]
    pub estimated_disk_mb: u64,
    /// Overall implementation difficulty, assessed before the build starts.
    #[serde(default)]
    pub difficulty: Complexity,
    /// Total token budget for the whole project (input + output).
    #[serde(default)]
    pub estimated_tokens: u64,
    /// Model label the token estimate was made for.
    #[serde(default)]
    pub token_estimate_model: String,
    #[serde(default)]
    pub milestones: Vec<MilestoneSpec>,
}

impl ProjectSpec {
    /// A project skeleton derived directly from a raw idea, used when the brain
    /// is unavailable or returns fewer projects than requested.
    pub fn from_idea(idea: &Idea, slug: String) -> Self {
        let title = idea
            .title
            .clone()
            .unwrap_or_else(|| first_sentence(&idea.details, 60));
        ProjectSpec {
            slug,
            title,
            idea: idea.details.clone(),
            summary: String::new(),
            questions: Vec::new(),
            answers: BTreeMap::new(),
            acceptance_criteria: Vec::new(),
            assumptions: Vec::new(),
            risks: Vec::new(),
            stack: Vec::new(),
            compute: ComputeNeed::Light,
            needs_vps: false,
            estimated_disk_mb: 512,
            difficulty: Complexity::Medium,
            estimated_tokens: 0,
            token_estimate_model: String::new(),
            milestones: Vec::new(),
        }
    }

    /// Apply answers from an `answers.toml` file (`[projects.<slug>]` table).
    pub fn apply_answers(&mut self, table: &toml::value::Table) {
        let projects = table.get("projects").and_then(|v| v.as_table());
        let Some(projects) = projects else { return };
        let Some(entry) = projects.get(&self.slug).and_then(|v| v.as_table()) else {
            return;
        };
        for (key, value) in entry {
            let text = match value {
                toml::Value::String(s) => s.clone(),
                other => other.to_string(),
            };
            if text.trim().is_empty() {
                continue;
            }
            if let Some(question) = self.questions.iter_mut().find(|q| &q.id == key) {
                // Mark the question as answered by mirroring the value.
                question.default = Some(text.clone());
            }
            self.answers.insert(key.clone(), text);
        }
    }

    /// All questions that still have no answer (ignoring blank answers).
    pub fn unanswered(&self) -> Vec<&Question> {
        self.questions
            .iter()
            .filter(|q| {
                self.answers
                    .get(&q.id)
                    .map(|a| a.trim().is_empty())
                    .unwrap_or(true)
            })
            .collect()
    }

    /// Answers formatted for prompts.
    pub fn answer_lines(&self) -> Vec<String> {
        self.answers
            .iter()
            .filter(|(_, a)| !a.trim().is_empty())
            .map(|(id, answer)| {
                let question = self
                    .questions
                    .iter()
                    .find(|q| &q.id == id)
                    .map(|q| q.question.as_str())
                    .unwrap_or(id.as_str());
                format!("- Q ({id}): {question}\n  A: {answer}")
            })
            .collect()
    }
}

/// The whole plan: every project the user asked for.
#[derive(Debug, Clone, PartialEq, Serialize, Deserialize, Default)]
pub struct Plan {
    #[serde(default)]
    pub created_at: String,
    #[serde(default)]
    pub source: String,
    /// Stable hash of the ideas file used to build this plan.
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub source_hash: Option<String>,
    /// Hardware profile used for the planning call (best effort).
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub host: Option<crate::host::HostProfile>,
    /// A human explicitly approved this exact plan for execution.
    #[serde(default)]
    pub approved: bool,
    /// When the approval was recorded.
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub approved_at: Option<String>,
    #[serde(default)]
    pub specs: Vec<ProjectSpec>,
}

impl Plan {
    pub fn get(&self, slug: &str) -> Option<&ProjectSpec> {
        self.specs.iter().find(|s| s.slug == slug)
    }

    pub fn get_mut(&mut self, slug: &str) -> Option<&mut ProjectSpec> {
        self.specs.iter_mut().find(|s| s.slug == slug)
    }
}

/// Lifecycle of one project.
#[derive(Debug, Clone, Copy, PartialEq, Eq, Serialize, Deserialize, Default)]
#[serde(rename_all = "lowercase")]
pub enum ProjectStatus {
    #[default]
    Planned,
    Scaffolded,
    Running,
    Completed,
    Failed,
    Stopped,
    Archived,
}

impl ProjectStatus {
    pub fn as_str(&self) -> &'static str {
        match self {
            ProjectStatus::Planned => "planned",
            ProjectStatus::Scaffolded => "scaffolded",
            ProjectStatus::Running => "running",
            ProjectStatus::Completed => "completed",
            ProjectStatus::Failed => "failed",
            ProjectStatus::Stopped => "stopped",
            ProjectStatus::Archived => "archived",
        }
    }
}

/// Persisted state for one project.
#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize)]
pub struct ProjectState {
    pub slug: String,
    #[serde(default)]
    pub title: String,
    #[serde(default)]
    pub path: String,
    #[serde(default)]
    pub repo_url: String,
    #[serde(default)]
    pub status: ProjectStatus,
    #[serde(default)]
    pub cores: Vec<usize>,
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub pid: Option<u32>,
    #[serde(default)]
    pub log_path: String,
    #[serde(default)]
    pub compute: ComputeNeed,
    #[serde(default)]
    pub needs_vps: bool,
    #[serde(default)]
    pub created_at: String,
    #[serde(default)]
    pub updated_at: String,
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub exit_code: Option<i32>,
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub last_error: Option<String>,
    /// Set by a human with `mox vps allow <slug>`. Remote deployment is refused
    /// without it.
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub vps_approved_at: Option<String>,
    #[serde(default)]
    pub vps_approved_note: String,
    /// Duration of the last agent run, in seconds.
    #[serde(default)]
    pub duration_secs: u64,
    /// How many times an agent has been launched for this project.
    #[serde(default)]
    pub attempts: u32,
    /// Last execution target: local, vps or a remote alias.
    #[serde(default = "default_target")]
    pub target: String,
    /// Pid of a detached remote run (survives the local machine).
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub remote_pid: Option<u32>,
}

fn default_target() -> String {
    "local".to_string()
}

impl ProjectState {
    pub fn new(slug: &str, title: &str, path: &str) -> Self {
        let now = crate::util::now_rfc3339();
        ProjectState {
            slug: slug.to_string(),
            title: title.to_string(),
            path: path.to_string(),
            repo_url: String::new(),
            status: ProjectStatus::Planned,
            cores: Vec::new(),
            pid: None,
            log_path: String::new(),
            compute: ComputeNeed::Light,
            needs_vps: false,
            created_at: now.clone(),
            updated_at: now,
            exit_code: None,
            last_error: None,
            vps_approved_at: None,
            vps_approved_note: String::new(),
            duration_secs: 0,
            attempts: 0,
            target: "local".to_string(),
            remote_pid: None,
        }
    }
}

fn first_sentence(text: &str, max: usize) -> String {
    let first = text
        .split(['.', '\n'])
        .next()
        .unwrap_or(text)
        .trim()
        .to_string();
    crate::util::truncate_chars(&first, max)
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn complexity_weights_and_parsing() {
        assert_eq!("very-high".parse::<Complexity>().unwrap().weight(), 5);
        assert_eq!("LOW".parse::<Complexity>().unwrap().weight(), 1);
        assert!("nope".parse::<Complexity>().is_err());
        assert_eq!(Complexity::High.as_str(), "high");
    }

    #[test]
    fn compute_need_parsing() {
        assert_eq!("Heavy".parse::<ComputeNeed>().unwrap(), ComputeNeed::Heavy);
        assert_eq!("low".parse::<ComputeNeed>().unwrap(), ComputeNeed::Light);
        assert!("quantum".parse::<ComputeNeed>().is_err());
    }

    #[test]
    fn spec_from_idea_uses_title() {
        let idea = Idea {
            title: Some("Budget Buddy".into()),
            details: "Track my spending. And more.".into(),
            raw: String::new(),
        };
        let spec = ProjectSpec::from_idea(&idea, "budget-buddy".into());
        assert_eq!(spec.title, "Budget Buddy");
        assert_eq!(spec.slug, "budget-buddy");
        assert_eq!(spec.estimated_disk_mb, 512);
        assert_eq!(spec.difficulty, Complexity::Medium);
        assert_eq!(spec.estimated_tokens, 0);
        assert!(spec.token_estimate_model.is_empty());
        assert!(spec.milestones.is_empty());
    }

    #[test]
    fn spec_from_idea_derives_title_from_text() {
        let idea = Idea {
            title: None,
            details: "A tiny web server for metrics. Extra sentence.".into(),
            raw: String::new(),
        };
        let spec = ProjectSpec::from_idea(&idea, "a-tiny".into());
        assert_eq!(spec.title, "A tiny web server for metrics");
    }

    #[test]
    fn apply_answers_from_toml() {
        let mut spec = ProjectSpec::from_idea(
            &Idea {
                title: Some("X".into()),
                details: "x".into(),
                raw: String::new(),
            },
            "x".into(),
        );
        spec.questions = vec![Question {
            id: "q1".into(),
            question: "Which DB?".into(),
            why: None,
            default: None,
        }];
        let table: toml::value::Table = toml::from_str(
            r#"
[projects.x]
q1 = "PostgreSQL"
q2 = ""
"#,
        )
        .unwrap();
        spec.apply_answers(&table);
        assert_eq!(spec.answers.get("q1").unwrap(), "PostgreSQL");
        assert!(!spec.answers.contains_key("q2"));
        assert!(spec.unanswered().is_empty());
    }

    #[test]
    fn answer_lines_include_question_text() {
        let mut spec = ProjectSpec::from_idea(
            &Idea {
                title: Some("X".into()),
                details: "x".into(),
                raw: String::new(),
            },
            "x".into(),
        );
        spec.questions.push(Question {
            id: "q1".into(),
            question: "Which DB?".into(),
            why: None,
            default: None,
        });
        spec.answers.insert("q1".into(), "SQLite".into());
        let lines = spec.answer_lines();
        assert_eq!(lines.len(), 1);
        assert!(lines[0].contains("Which DB?"));
        assert!(lines[0].contains("SQLite"));
    }

    #[test]
    fn status_serde_roundtrip() {
        let json = serde_json::to_string(&ProjectStatus::Completed).unwrap();
        assert_eq!(json, "\"completed\"");
        let back: ProjectStatus = serde_json::from_str(&json).unwrap();
        assert_eq!(back, ProjectStatus::Completed);
    }
}
